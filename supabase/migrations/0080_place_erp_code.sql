-- 0080_place_erp_code.sql
-- ERP(IBCENTER) 거래처코드를 사업장에 붙인다.
--
-- 왜 사업장(entity 아님)인가: ERP 는 사업자번호마다 거래처를 따로 만든다.
-- 실측 — 시파사 사업장 3곳 = 코드 3개(72140/72141/72142), 원창에코 2곳 = 04141/44636,
-- 나우오어네버 2곳 = 56707/68694. 한 거래처명 = 한 코드로 1:1이었다.
-- 다만 지점 청구를 본점으로 몰아 쓰는 곳이 있어(한일디아이) 코드 없는 사업장이 남는다 → nullable.
--
-- 이 코드는 ERP 원장의 '거래처코드'다. 대사 시 사업자번호보다 이 코드가 정확하다
-- (원장에는 사업자번호가 없고 코드만 있다).

alter table public.biz_place add column if not exists erp_client_code text;

comment on column public.biz_place.erp_client_code is
  'ERP(IBCENTER) 거래처코드 5자리. 사업장 단위. 월별 ERP 원장 대사의 연결키.';

create unique index if not exists biz_place_erp_client_code_key
  on public.biz_place (erp_client_code) where erp_client_code is not null;

