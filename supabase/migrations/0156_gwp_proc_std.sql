-- 0156 일반조서 — 2120A 주요 감사절차(K열) 표준(사용자 2026-09-30).
--
-- 2120A 에서 Material(잔액 > 중요성)·Unexpected(증감 > 중요성×90%)가 뜬 계정은 K열 「주요 ToD 절차」를 적어야 한다.
-- 해마다 금액에 따라 달라지므로 표준 세팅이 필요 — 화면에서 고치는 표(사용자 결정 (나)).
--   계정(동의어) × 판정(항상·Material·Unexpected) × 업종(공통·제조업 …) 한 줄에 절차 하나.
--   제안할 때는 공통 + 그 회사 업종 줄만 쓴다 — 「미정산 운송건」 같은 문구가 제조업 회사에 붙지 않게(평안정공 실물).
--   계정 「*」 은 계정별 줄이 없을 때 쓰는 기본 절차.
--   문구의 {증감액}·{증감률}·{잔액} 은 그 줄 금액으로 채운다(「1억 이상 증가」처럼 숫자를 문장에 고정하지 않는다).
-- 업종은 회사마다 — 일반조서 당기 세팅(gwp_year.industry). 처음엔 재무제표로 추정하고 담당자가 확인한다.

create table if not exists public.gwp_proc_std (
  id uuid primary key default gen_random_uuid(),
  account text not null,
  aliases text[] not null default '{}',
  trigger text not null check (trigger in ('항상', 'Material', 'Unexpected')),
  industry text not null default '공통',
  body text not null,
  sort int not null default 100,
  active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now()
);
create index if not exists gwp_proc_std_account on public.gwp_proc_std (account);

alter table public.gwp_proc_std enable row level security;
drop policy if exists gwp_proc_std_sel on public.gwp_proc_std;
create policy gwp_proc_std_sel on public.gwp_proc_std for select using (public.is_audit_staff());
drop policy if exists gwp_proc_std_ins on public.gwp_proc_std;
create policy gwp_proc_std_ins on public.gwp_proc_std for insert
  with check (public.is_audit_staff() and not public.is_readonly());
drop policy if exists gwp_proc_std_upd on public.gwp_proc_std;
create policy gwp_proc_std_upd on public.gwp_proc_std for update
  using (public.is_audit_staff() and not public.is_readonly())
  with check (public.is_audit_staff() and not public.is_readonly());
drop policy if exists gwp_proc_std_del on public.gwp_proc_std;
create policy gwp_proc_std_del on public.gwp_proc_std for delete
  using (public.is_audit_staff() and not public.is_readonly());

alter table public.gwp_year add column if not exists industry text;

