-- 0144 주석의 기본 상태를 「작업중」으로
--
-- 작년 감사보고서에서 주석 목록을 가져오면 **대부분이 올해도 그대로 쓰인다.** 목록에 올라온
-- 순간 이미 할 일이 정해져 있는 셈이라, 처음부터 「미할당」으로 두면 전부 손으로 바꿔야 한다.
-- 「미할당」은 담당을 아직 못 정한 예외를 표시할 때만 쓴다(사용자 지시 2026-09-12).
--
-- 앱은 상태를 늘 명시해서 넣지만(lib/dsdNotes.ts DEFAULT_STATUS), 표의 기본값도 같이 맞춘다 —
-- 두 곳이 어긋나면 나중에 SQL 로 한 줄 넣을 때 조용히 다른 값이 들어간다.
alter table public.dsd_note alter column status set default '작업중';

comment on column public.dsd_note.status is
  '진행 상태. 새로 만들면 「작업중」 — 작년에서 가져온 주석은 올해도 대개 그대로 쓰인다.';
