// 조서 시트 차례 — 번호 순서, 딸림 시트는 제 조서 뒤, 앞쪽 공통 시트는 그대로.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { byCodeOrder, isCodeOrdered, orderKey } from './gwpOrder';

test('차례 열쇠 — 「-1」이 글자 꼬리보다 앞, 꼬리 괄호·(소규모)는 무시', () => {
  const ks = ['2110A', '2110-2', '2110', '2110-1', '2700A-1(적용지침)', '2700A (소규모)', '2700A-2(감사계획단계)', '2700'].map((n) => [n, orderKey(n)!] as const);
  assert.deepEqual([...ks].sort((a, b) => (a[1] < b[1] ? -1 : 1)).map((x) => x[0]), ['2110', '2110-1', '2110-2', '2110A', '2700', '2700A (소규모)', '2700A-1(적용지침)', '2700A-2(감사계획단계)']);
  assert.equal(orderKey('감사조서목록'), null);
});

test('늘어놓기 — 맨 뒤에 붙은 새 시트가 제자리로, 딸림(조직도·8110ARP_BS)은 제 조서 뒤, 같은 번호는 원래 차례', () => {
  const names = ['감사조서철 작성 및 보존', '조서표지(공통사항)', '감사조서목록', '1100(소규모)', '1200(소규모)', '2100(소규모)', '2100A', '조직도',
    '2110(소규모)', '2700A-2(소규모)', '8100', '8110', '8110ARP_BS', '8110ARP_PL', '8700', '1200', '2100', '2110', '2700A-2(감사계획단계)', '2700A-4(감사완결단계)'];
  assert.deepEqual(byCodeOrder(names), ['감사조서철 작성 및 보존', '조서표지(공통사항)', '감사조서목록', '1100(소규모)', '1200(소규모)', '1200', '2100(소규모)', '2100',
    '2100A', '조직도', '2110(소규모)', '2110', '2700A-2(소규모)', '2700A-2(감사계획단계)', '2700A-4(감사완결단계)', '8100', '8110', '8110ARP_BS', '8110ARP_PL', '8700']);
  assert.equal(isCodeOrdered(byCodeOrder(names)), true);
  assert.equal(isCodeOrdered(names), false);
});
