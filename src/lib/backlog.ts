/** 항목에 붙는 꼬리표. 색이 뜻을 나른다. */
export type Tone = 'due' | 'gold' | 'plain';

export interface BacklogTag {
  label: string;
  tone?: Tone;
}

export interface BacklogItem {
  /** 왼쪽 표식 — 번호(로드맵 4·5·6), 기호(①②③), '!'(기한), '→'(대기), '·'(보류). */
  mark: string;
  title: string;
  /**
   * 한두 문장. 강조는 <b> **하나만** 해석된다 — code·i 같은 다른 태그를 쓰면
   * 화면에 글자 그대로 나온다(BacklogTab 의 bold() 가 <b> 만 가르기 때문).
   */
  desc: string;
  tags?: BacklogTag[];
}

export interface BacklogSection {
  id: string;
  /** 눈썹 라벨 — 이 묶음이 무엇인지. */
  eyebrow: string;
  title: string;
  /** 묶음 전체에 붙는 한 줄(선택). */
  note?: string;
  /** 강조 색 — 기한 있는 묶음만 'due'. */
  tone?: Tone;
  items: BacklogItem[];
}

