test('기장팀 비용(현금주의) — 전달 계상 원장이 없으면 7월 공단 납부는 사원 구분 없이, 알림', () => {
  const S = (acct: string, slip: string, dr: number, cr: number, name: string): LedgerLine => ({ acct, slip, code: '', name, dr, cr, sum: '건강보험(법인)', staff: '정남지' });
  const { rows, notes } = aggregateCosts([S('미지급금', '25-0710-0010', 397510, 0, '국민건강보험공단'), S('본지점', '25-0710-0010', 0, 397510, '')], '2025-07-01', '2026-06-30');
  assert.equal(rows.find((r) => r.sub === '4대보험' && r.staff === '')?.amount, 397510);
  assert.equal(notes.length, 1);
});
