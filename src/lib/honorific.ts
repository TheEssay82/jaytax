// 담당자 이름에 호칭을 붙이는 규칙 **한 곳**.
//
// 왜 필요한가: 화면이 `이름 + ' ' + 호칭` 을 그냥 이어 붙였는데, 이름 칸에 이미 「…님」이
// 들어 있는 자료가 47건 있어 <b>「공나영 대표님 님」</b> 처럼 두 번 붙었다(2026-09-05 확인).
// 자료는 고쳤지만, 앞으로 누가 또 「…님」으로 넣어도 화면이 이상해지지 않게 여기서 막는다.

/**
 * 직책으로 끝나는가 — 그러면 호칭을 붙여 쓴다(「공나영 대표님」).
 * 띄어쓰기 여부로 가르면 「강성제매니저 님」처럼 어색해진다.
 */
const TITLE = /(대표|사장|부사장|전무|상무|이사|본부장|실장|팀장|부장|차장|과장|대리|주임|사원|매니저|회계사|세무사|변호사|원장|소장|점장|반장|기사|선생|교수|박사|의원|위원|국장|과장님?)$/;

/** 「어머님·아버님·사모님」은 통째로 하나의 호칭이라 떼면 말이 안 된다. */
const WHOLE = /(어머|아버|사모)님$/;

/** 이름 끝의 「님」을 뗀다. 통호칭(어머님 등)은 그대로 둔다. */
export function stripHonorific(name: string): string {
  const s = (name ?? '').trim();
  if (WHOLE.test(s)) return s;
  return s.replace(/\s*님$/, '').trim();
}

/**
 * 화면에 쓸 이름 — **「님」은 한 번만** 붙는다.
 *
 * · 이름이 이미 「…님」으로 끝나면 호칭을 덧붙이지 않는다.
 * · 「대표·과장」처럼 직책으로 끝나면 <b>붙여 쓴다</b>(「공나영 대표님」) — 「공나영 대표 님」은 어색하다.
 * · 그 밖에는 띄어 쓴다(「신가영 님」).
 */
export function displayName(name: string, honorific = '님'): string {
  const s = (name ?? '').trim();
  const h = (honorific ?? '').trim();
  if (!s) return '';
  if (!h) return s;
  if (s.endsWith(h)) return s;          // 이미 붙어 있다
  // 직책으로 끝나면 붙여 쓴다(「공나영 대표님」·「강성제매니저님」).
  // 띄어쓰기 여부로 가르면 「강성제매니저 님」처럼 어색해지므로 **직책 낱말**로 가른다.
  return TITLE.test(s) ? `${s}${h}` : `${s} ${h}`;
}
